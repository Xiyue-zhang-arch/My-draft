changes = []
for before, after, rule in edits:
    n = text.count(before)
    if n != 1:
        raise ValueError(f'Expected exactly one match, found {n}: {before}')
    line = text[:text.index(before)].count('\n') + 1
    changes.append({'line': line, 'rule': rule, 'before': before, 'after': after})
    text = text.replace(before, after, 1)

def signature(s):
    # Protect every numeric token and structural or scientific LaTeX command.
    return {
        'numbers': re.findall(r'(?<![A-Za-z])[0-9]+(?:\.[0-9]+)?', s),
        'commands': re.findall(r'\\(?:begin|end|chapter\*?|section|subsection|label|ref|eqref|includegraphics|cite)(?:\[[^\]]*\])?\{[^}]*\}', s),
        'citations': re.findall(r'\{\[\}[^\n]*?\{\]\}', s),
        'formulas': re.findall(r'\\begin\{(?:equation|align|gather)\}.*?\\end\{(?:equation|align|gather)\}', s, re.S),
    }

old_sig, new_sig = signature(original), signature(text)
for key in old_sig:
    if old_sig[key] != new_sig[key]:
        raise ValueError('Protected content changed: ' + key)

TARGET.mkdir(parents=True, exist_ok=True)
shutil.copytree(SOURCE / 'media', TARGET / 'media', dirs_exist_ok=True)
for filename in ['物理特征文献依据对照.md', 'boxplot_seed_values.csv', 'class_recall_sd_values.csv', 'cost_sd_values.csv']:
    shutil.copy2(SOURCE / filename, TARGET / filename)
(TARGET / 'thesis.tex').write_text(text, encoding='utf-8')
(TARGET / '语言修订记录.json').write_text(json.dumps(changes, ensure_ascii=False, indent=2), encoding='utf-8')
diff = ''.join(difflib.unified_diff(original.splitlines(keepends=True), text.splitlines(keepends=True), fromfile='修改前/thesis.tex', tofile='修改后/thesis.tex'))
(TARGET / '语言修订对照.diff').write_text(diff, encoding='utf-8')
print(f'Applied {len(changes)} reviewed changes; numeric tokens, citations, formulas and structure match.')
