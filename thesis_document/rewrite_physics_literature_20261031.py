def subsection(name, content):
    global s
    pat=r'(\\subsection\{'+re.escape(name)+r'\}\\label\{[^}]+\}\s*).*?(?=\\(?:subsection|section)\{)'
    s,n=re.subn(pat,lambda m:m.group(1)+'\n'+content.strip()+'\n\n',s,count=1,flags=re.S)
    assert n==1,name

